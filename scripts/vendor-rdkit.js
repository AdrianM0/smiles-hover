#!/usr/bin/env node
/**
 * Copy the RDKit MinimalLib WASM build out of node_modules into vendor/.
 *
 * node_modules is excluded from the packaged .vsix, but the extension needs
 * these two files at runtime, so they get vendored in as part of the build.
 */
const fs = require("fs");
const path = require("path");

const pkgRoot = path.join(__dirname, "..", "node_modules", "@rdkit", "rdkit");
const src = path.join(pkgRoot, "dist");
const dest = path.join(__dirname, "..", "vendor");

const FILES = ["RDKit_minimal.js", "RDKit_minimal.wasm"];

if (!fs.existsSync(src)) {
  console.error(`RDKit dist not found at ${src} — run 'npm install' first.`);
  process.exit(1);
}

fs.mkdirSync(dest, { recursive: true });
for (const f of FILES) {
  fs.copyFileSync(path.join(src, f), path.join(dest, f));
  const { size } = fs.statSync(path.join(dest, f));
  console.log(`vendor/${f} (${(size / 1024 / 1024).toFixed(1)} MB)`);
}

// BSD-3-Clause clause 2 requires binary redistributions to reproduce the
// copyright notice, conditions, and disclaimer in the materials shipped
// alongside. We ship the WASM binary, so the notice has to travel with it.
// Generated from the installed package rather than copy-pasted, so an RDKit
// upgrade can't leave a stale notice behind.
const version = JSON.parse(
  fs.readFileSync(path.join(pkgRoot, "package.json"), "utf8")
).version;
const license = fs.readFileSync(path.join(pkgRoot, "LICENSE"), "utf8").trim();

const notices = `# Third-party notices

SMILES Hover bundles the following third-party software. This file is
generated by \`scripts/vendor-rdkit.js\`; edit that script, not this file.

## RDKit (@rdkit/rdkit ${version})

Distributed as \`vendor/RDKit_minimal.js\` and \`vendor/RDKit_minimal.wasm\`.
Upstream: https://github.com/rdkit/rdkit

${license}
`;

fs.writeFileSync(path.join(__dirname, "..", "THIRD-PARTY-NOTICES.md"), notices);
console.log(`THIRD-PARTY-NOTICES.md (RDKit ${version})`);
